#include <iostream>
using namespace std;

int main()
{
    int a, b;
    cout << "ENTER NUMBER: ";
    cin >> a;
    cout << "ENTER NUMBER: ";
    cin >> b;
    cout << "SUM OF TWO NUMBER IS: " << a + b << endl;
    cout << "PRODUCT OF TWO NUMBER IS: " << a * b << endl;
    cout << "SUBSTRACT IF TWO NUMBER IS: " << a - b << endl;
    cout << "QUOTIENT OF TWO NUMBER IS: " << a / b << endl;
    cout << "REMAINDER OF TWO NUMBER IS: " << a % b << endl;
}